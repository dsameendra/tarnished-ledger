// Builds js/data/counter-markers.js from the shipped marker file assets/map/data/dlc.json.
//   node scripts/counter-markers.mjs        rewrites the file
// scripts/check.mjs imports counterMarkersSource() and fails when the committed file differs, and
// scripts/build-map-data.mjs runs it after writing dlc.json, so the two never drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const FILE = join(root, "js/data/counter-markers.js");
// Blessing counter -> map category of the markers that feed it.
const CATEGORY = { sf: 11317, rsa: 11316 };

export function counterMarkersSource(rows) {
  const markers = {}, qty = {};
  for (const [id, cat] of Object.entries(CATEGORY)) {
    markers[id] = [];
    for (const r of rows.filter((x) => x[1] === cat)) {
      markers[id].push(String(r[0]));
      // A pile is titled "Scadutree Fragment x2": finding that marker is worth its quantity.
      const q = Number((/ x(\d+)$/.exec(r[4]) || [])[1]) || 1;
      if (q > 1) qty[String(r[0])] = q;
    }
  }
  return `// Map markers that count toward a blessing counter: finding one adds its quantity to the counter (a marker titled
// "Scadutree Fragment x2" adds 2), so the counter is the quantity found plus whatever you added by hand.
// Generated by scripts/counter-markers.mjs from assets/map/data/dlc.json (categories 11317 and 11316). Do not edit by hand.
export const COUNTER_MARKERS = ${JSON.stringify(markers)};
// Quantity of the markers that are worth more than one (everything else is worth 1).
export const COUNTER_QTY = ${JSON.stringify(qty)};
`;
}

export const readRows = () => JSON.parse(readFileSync(join(root, "assets/map/data/dlc.json"), "utf8"));

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(FILE, counterMarkersSource(readRows()));
  console.log("wrote", FILE);
}
