const paths = {};
const cache = new Map();
const path = (g) => paths[g] || (paths[g] = new Path2D(D[g] || D.misc));

// Sprite for one glyph: (size + 6) css px square, the extra 3px per side holds the outline.
export function sprite(glyph, color, size, dpr = 1) {
  const key = `${glyph}|${color}|${size}|${dpr}`;
  let cv = cache.get(key);
  if (cv) return cv;
  const full = size + 6;
  cv = document.createElement("canvas");
  cv.width = cv.height = Math.ceil(full * dpr);
  const x = cv.getContext("2d");
  const r = size / 2;
  x.scale(dpr, dpr);
  x.translate(full / 2, full / 2);
  x.scale(r, r);
  x.lineJoin = "round";
  const pa = path(glyph);
  x.lineWidth = 3.4 / r; x.strokeStyle = "#14130e"; x.stroke(pa);
  x.lineWidth = 1.8 / r; x.strokeStyle = "#fffdf6"; x.stroke(pa);
  x.fillStyle = color; x.fill(pa, "evenodd");
  cv.full = full;
  cache.set(key, cv);
  return cv;
}

export const iconURL = (glyph, color, size = 20) => sprite(glyph, color, size, 2).toDataURL();
